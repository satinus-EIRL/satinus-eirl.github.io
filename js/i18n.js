  function isLang(lang) {
    return LANGS.indexOf(lang) !== -1;
  }

  function getLang() {
    var params = new URLSearchParams(window.location.search);
    var fromUrl = params.get('lang');
    if (isLang(fromUrl)) {
      try { localStorage.setItem(STORAGE_KEY, fromUrl); } catch (e) { /* ignore */ }
      return fromUrl;
    }
    try {
      var stored = localStorage.getItem(STORAGE_KEY);
      if (isLang(stored)) return stored;
    } catch (e) { /* ignore */ }
    var htmlLang = (document.documentElement.lang || '').slice(0, 2);
    return isLang(htmlLang) ? htmlLang : DEFAULT_LANG;
  }

  function t(key, lang, vars) {
    var bag = STRINGS[lang] || STRINGS[DEFAULT_LANG];
    var str = bag[key] || STRINGS[DEFAULT_LANG][key] || key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
      });
    }
    return str;
  }

  function pickLocalized(obj, field) {
    if (!obj) return '';
    var lang = getLang();
    if (lang === 'en' && obj[field + 'En']) return obj[field + 'En'];
    if (lang === 'pt' && obj[field + 'Pt']) return obj[field + 'Pt'];
    return obj[field] || '';
  }

  function applyTranslations(lang) {
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      el.textContent = t(key, lang);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      el.placeholder = t(el.getAttribute('data-i18n-placeholder'), lang);
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'), lang));
    });
    document.querySelectorAll('title[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      var val = t(key, lang);
      el.textContent = val;
      document.title = val;
    });
    document.querySelectorAll('meta[data-i18n-content]').forEach(function (el) {
      el.setAttribute('content', t(el.getAttribute('data-i18n-content'), lang));
    });
    document.querySelectorAll('.lang-switcher button').forEach(function (btn) {
      var btnLang = btn.getAttribute('data-lang');
      btn.classList.toggle('is-active', btnLang === lang);
      btn.setAttribute('aria-pressed', btnLang === lang ? 'true' : 'false');
    });
    window.dispatchEvent(new CustomEvent('satinus:lang', { detail: { lang: lang } }));
  }

  function setLang(lang) {
    if (!isLang(lang)) return;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* ignore */ }
    applyTranslations(lang);
  }

  function initLangSwitcher() {
    document.querySelectorAll('.lang-switcher').forEach(function (wrap) {
      wrap.addEventListener('click', function (e) {
        var btn = e.target.closest('[data-lang]');
        if (!btn) return;
        setLang(btn.getAttribute('data-lang'));
      });
    });
  }

  window.SatinusI18n = {
    getLang: getLang,
    setLang: setLang,
    t: function (key, vars) { return t(key, getLang(), vars); },
    pick: pickLocalized,
    apply: function () { applyTranslations(getLang()); },
    langs: LANGS,
  };

  document.addEventListener('DOMContentLoaded', function () {
    applyTranslations(getLang());
    initLangSwitcher();
  });
